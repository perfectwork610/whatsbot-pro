// Only known system messages are translated. Customer messages, account names,
// template identifiers, and configured outbound text are never passed here.
export function translate(locale: Locale, message: string): string {
  if (locale === 'pt-BR') return message === 'Workspace' ? 'Espaço de trabalho' : message;
  if (message === 'Workspace') return 'Workspace';
  if (english[message]) return english[message];
  const patterns: [RegExp, (...parts: string[]) => string][] = [
    [/^Servidor indisponível \((\d+)\)\.$/, (code) => `Server unavailable (${code}).`],
    [
      /^(\d+) importados · (\d+) duplicados · (\d+) inválidos$/,
      (a, b, c) => `${a} imported · ${b} duplicates · ${c} invalid`,
    ],
    [/^(\d+) com permissão$/, (n) => `${n} with permission`],
    [/^(\d+) simulações$/, (n) => `${n} simulations`],
    [/^(\d+) campanhas ativas$/, (n) => `${n} active campaigns`],
    [/^(\d+) contas cadastradas$/, (n) => `${n} accounts added`],
    [/^(.+) obrigatório\.$/, (name) => `${english[name] || name} is required.`],
    [
      /^Configure (WA_TOKEN_[A-Z0-9_]+) no servidor\.$/,
      (name) => `Configure ${name} on the server.`,
    ],
    [
      /^Importação: (\d+) novos, (\d+) duplicados, (\d+) inválidos\.$/,
      (a, b, c) => `Import: ${a} new, ${b} duplicates, ${c} invalid.`,
    ],
    [
      /^Permissão atualizada para (.+): (true|false)\.$/,
      (phone, value) => `Permission updated for ${phone}: ${value}.`,
    ],
    [/^Conta (.+) cadastrada\.$/, (name) => `Account ${name} added.`],
    [/^Modelos sincronizados: (.+)\.$/, (name) => `Templates synced: ${name}.`],
    [
      /^Campanha (.+) criada com (\d+) destinatários\.$/,
      (name, n) => `Campaign ${name} created with ${n} recipients.`,
    ],
    [/^Campanha (.+): (running|paused)\.$/, (name, status) => `Campaign ${name}: ${status}.`],
    [
      /^Campanha (.+) pausada: modelo não aprovado\.$/,
      (name) => `Campaign ${name} paused: template not approved.`,
    ],
    [/^Descadastro solicitado por (.+)\.$/, (phone) => `Unsubscribe requested by ${phone}.`],
    [
      /^Envio falhou; campanha pausada\. (.+)$/,
      (error) => `Send failed; campaign paused. ${translate(locale, error)}`,
    ],
    [/^Error: (.+)$/, (error) => `Error: ${translate(locale, error)}`],
  ];
  for (const [pattern, format] of patterns) {
    const match = message.match(pattern);
    if (match) return format(...match.slice(1));
  }
  return message;
}

export function resolveLocale(saved: string | null, browser: string): Locale {
  return saved === 'en' || saved === 'pt-BR'
    ? saved
    : browser.toLowerCase().startsWith('pt')
      ? 'pt-BR'
      : 'en';
}

