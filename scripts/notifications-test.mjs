import assert from 'node:assert/strict';
import { notificationKey, markNotificationsRead } from '../lib/notifications.ts';
const legacy = {at: '2026-11-14T00:00:00Z', text: 'Legacy event'};
const first = {id: 'one', at: legacy.at, text: 'First event'};
const second = {id: 'two', at: legacy.at, text: 'Second event'};
const events = [first, second, legacy];
markNotificationsRead(events, [notificationKey(first)]);
assert.ok(first.readAt);
assert.equal(second.readAt, undefined);
const markedAt = first.readAt;
const snapshot = events.filter(e => !e.readAt).map(notificationKey);
events.unshift({id: 'new', at: legacy.at, text: 'Arrived after snapshot'});
markNotificationsRead(events, snapshot);
assert.ok(legacy.readAt, 'legacy events support stable read state');
assert.ok(second.readAt);
assert.equal(events[0].readAt, undefined, 'new activity must remain unread');
markNotificationsRead(events, ['one']);
assert.equal(first.readAt, markedAt, 'marking read is idempotent');
assert.throws(() => markNotificationsRead(events, ['one', null]), /inválidas/);
console.log('Notification read state, legacy events, idempotency, and new-event race checks passed.');
